// dateKey(YYYY-MM-DD)를 받아 해당 날짜의 본문(day)을 찾아 반환.
// 평일(월~금)만 본문이 있고, 토/일은 null을 반환.
export function getDailyPassage(dateKey) {
  const date = new Date(dateKey + 'T00:00:00')
  const dow = date.getDay() // 0=일 ... 6=토
  if (dow === 0 || dow === 6) return null

  for (const unit of UNITS) {
    const start = new Date(unit.startDate + 'T00:00:00')
    const diffDays = Math.floor((date - start) / 86400000)
    // 그 단원의 월요일부터 4주(28일, 평일 20일) 안에 있는지 대략적으로 확인
    if (diffDays < 0) continue

    const weekIndex = Math.floor(diffDays / 7)
    const dayInWeek = dow - 1 // 월=0 ... 금=4
    if (weekIndex === 0 && dayInWeek >= 0 && dayInWeek < unit.days.length) {
      return {
        unitId: unit.id,
        unitTitle: unit.title,
        dayIndex: dayInWeek,
        ...unit.days[dayInWeek],
        groupQuestions: unit.groupQuestions
      }
    }
  }
  return null
}
